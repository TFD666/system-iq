#!/usr/bin/env python
"""Generate a sample design and save it as a markdown file."""

import argparse
import json
import os
import sys
from datetime import date
from pathlib import PurePath

import httpx

PIPELINE_VERSION = "v1.0"


def _to_posix(path: str) -> str:
    """Forward slashes only, no leading "./" -- for building a GitHub URL from a
    local path. A Windows path like samples\\x.md must give samples/x.md."""
    posix = PurePath(path).as_posix()
    if posix.startswith("./"):
        posix = posix[2:]
    return posix


def _pct(probability) -> str:
    return f"{probability * 100:.0f}" if isinstance(probability, (int, float)) else "?"


def _validation_counts(validation: list) -> dict:
    counts = {"ok": 0, "possible": 0, "flagged": 0}
    for v in validation:
        status = v.get("status")
        if status in counts:
            counts[status] += 1
    return counts


def _non_ok(validation: list) -> list:
    return [v for v in validation if v.get("status") != "ok"]


def _print_validation_diagnostics(validation: list, counts: dict) -> None:
    """Ids, statuses and probabilities only -- never idea or design text."""
    for v in _non_ok(validation):
        print(f"  {v.get('id')} {v.get('status')} {_pct(v.get('probability'))}%")
    print(f"  ok={counts['ok']} possible={counts['possible']} flagged={counts['flagged']}")


def _build_header(today: str, max_flagged: int, max_possible: int, counts: dict, validation: list) -> str:
    comment = (
        f"<!-- SAMPLE: generated by System IQ on {today} "
        f"(pipeline {PIPELINE_VERSION}, rule: max-flagged {max_flagged}, max-possible {max_possible}), "
        f"not generated from your input. -->"
    )
    lines = [
        comment,
        f"SAMPLE: generated by System IQ on {today}. Not generated from your input.",
        f"Validation by Jev: {counts['ok']} ok, {counts['possible']} possible, {counts['flagged']} flagged",
    ]
    non_ok = _non_ok(validation)
    if non_ok:
        findings = ", ".join(
            f"{v.get('id')} ({v.get('status')} {_pct(v.get('probability'))}%)" for v in non_ok
        )
        lines.append(f"Findings: {findings}")
    return "\n".join(lines) + "\n\n"


def run(idea_file, title, out, api_url, mode, index_path=None, max_flagged=0, max_possible=0):
    """Run the sample generation. Returns 0 on success, 1 on failure."""
    with open(idea_file) as f:
        idea = f.read().strip()
    if not idea:
        print("ERROR: idea file is empty")
        return 1

    resp = httpx.post(
        f"{api_url}/design",
        json={
            "idea": idea,
            "stage": "validate",
            "writer_style": "confident",
            "max_revisions": 0,
            "mode": mode,
        },
        timeout=300,
    )
    if resp.status_code != 200:
        print(f"ERROR: API returned {resp.status_code}")
        return 1

    data = resp.json()
    md = data.get("design_markdown", "")
    val_status = data.get("meta", {}).get("validation_status", "")
    validation = data.get("validation") or []

    sections = [line for line in md.splitlines() if line.startswith("## ")]
    fallback_lines = [
        line for line in md.splitlines()
        if "could not be generated" in line.lower()
    ]
    counts = _validation_counts(validation)

    checks = []
    if len(sections) != 13:
        checks.append(f"sections: {len(sections)} (need 13)")
    if fallback_lines:
        checks.append(f"fallback lines: {len(fallback_lines)}")
    if val_status == "skipped":
        checks.append("validation status: skipped")
    if counts["flagged"] > max_flagged:
        checks.append(f"flagged: {counts['flagged']} (max {max_flagged})")
    if counts["possible"] > max_possible:
        checks.append(f"possible: {counts['possible']} (max {max_possible})")

    if checks:
        print("REJECTED. Failed checks:")
        for c in checks:
            print(f"  - {c}")
        _print_validation_diagnostics(validation, counts)
        return 1

    today = date.today().isoformat()
    header = _build_header(today, max_flagged, max_possible, counts, validation)

    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    with open(out, "w") as f:
        f.write(header + md)
    print(f"Saved: {out}")

    if index_path is None:
        index_path = os.path.join(
            os.path.dirname(out) or "samples", "index.json",
        )
    try:
        with open(index_path) as f:
            index = json.load(f)
        for entry in index:
            # Heal any older entry whose url was built from a raw Windows path.
            if isinstance(entry.get("url"), str):
                entry["url"] = entry["url"].replace("\\", "/")
    except (OSError, ValueError):
        index = []

    url = f"https://github.com/TFD666/system-iq/blob/main/{_to_posix(out)}"
    if not any(e.get("title") == title for e in index):
        index.append({"title": title, "url": url})
        with open(index_path, "w") as f:
            json.dump(index, f, indent=2)
        print(f"Updated: {index_path}")
    else:
        print("Title already in index, skipped update.")

    return 0


def main():
    parser = argparse.ArgumentParser(description="Generate a sample design.")
    parser.add_argument("--idea-file", required=True)
    parser.add_argument("--title", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--api-url", default="http://localhost:8000")
    parser.add_argument(
        "--mode", choices=["pipeline", "llm_only"], default="pipeline",
    )
    parser.add_argument("--max-flagged", type=int, default=0)
    parser.add_argument("--max-possible", type=int, default=0)
    args = parser.parse_args()
    sys.exit(run(
        args.idea_file, args.title, args.out, args.api_url, args.mode,
        max_flagged=args.max_flagged, max_possible=args.max_possible,
    ))


if __name__ == "__main__":
    main()
